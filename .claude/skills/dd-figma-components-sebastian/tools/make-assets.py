#!/usr/bin/env python3
"""Regenerate engine/figma-assets.js from assets/figma/ (Figma's Kiwi schema chunk + control samples).
Run: python3 -I tools/make-assets.py   (only needed if assets/figma/ changes)"""
import base64, json, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
F = ROOT / 'assets' / 'figma'
b64 = lambda name: base64.b64encode((F / name).read_bytes()).decode()
assets = {
    'figmaSchema': b64('clipboard-schema.deflate'), 'figmaControl': b64('control-data.deflate'),
    'figmaInstance': b64('control-instance.bin'), 'figmaInstanceMeta': (F / 'control-instance.meta').read_text().strip(),
    'figmaSet': b64('control-set.bin'), 'figmaSetMeta': (F / 'control-set.meta').read_text().strip(),
}
out = ROOT / 'engine' / 'figma-assets.js'
out.write_text("/* Generated by tools/make-assets.py from assets/figma/ — do not edit. Figma clipboard schema + control samples\n"
               "   (Grida fixtures, Apache-2.0; see NOTICE.md). */\nconst FIGMA_ASSETS = " + json.dumps(assets) + ";\n")
print(f'{out.relative_to(ROOT)}  {out.stat().st_size / 1024:.0f} KB')
