#!/usr/bin/env python3
"""Write @font-face rules with base64 TTF data URLs, so the Figma copy can read glyph outlines offline.

  python3 -I tools/inline-fonts.py --family "Inter" fonts/Inter-*.ttf --js > figma/fonts.js    # <script src="figma/fonts.js">
  python3 -I tools/inline-fonts.py --family "Inter" fonts/Inter-*.ttf > fonts.css               # paste into a <style> block / build step

Weight and italic are read from each file's OS/2 table. TrueType outlines (glyf) only: static .ttf files
(Google Fonts "static/" folder). Variable fonts and CFF .otf/.woff2 are refused, because the glyph reader can't
draw them. Don't load the CSS with <link rel="stylesheet">: on file:// Chrome treats a linked sheet as cross-origin and
the engine can't read it. Use --js (a script that adds a <style> block) or put the CSS inside <style>.
"""
import argparse, base64, pathlib, struct, sys

def tables(b):
    n = struct.unpack('>H', b[4:6])[0]
    return {b[12 + 16 * i:16 + 16 * i].decode('latin1'): struct.unpack('>II', b[20 + 16 * i:28 + 16 * i]) for i in range(n)}

ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
ap.add_argument('--family', required=True, help='CSS font-family name, exactly as your CSS uses it')
ap.add_argument('--js', action='store_true', help='write a script that injects the @font-face rules (works from file://)')
ap.add_argument('files', nargs='+')
a = ap.parse_args()
rules = []
for f in a.files:
    p = pathlib.Path(f); b = p.read_bytes()
    if b[:4] not in (b'\x00\x01\x00\x00', b'true'):
        sys.exit(f'{p.name}: not a TrueType .ttf (CFF .otf, .woff and .woff2 are not supported; use the static .ttf)')
    t = tables(b)
    if 'glyf' not in t: sys.exit(f'{p.name}: no glyf table')
    if 'fvar' in t: sys.exit(f'{p.name}: variable font; use one static .ttf per weight')
    o = t['OS/2'][0]; weight = struct.unpack('>H', b[o + 4:o + 6])[0]; italic = bool(struct.unpack('>H', b[o + 62:o + 64])[0] & 1)
    rules.append(f"@font-face {{ font-family: '{a.family}'; font-weight: {weight}; font-style: {'italic' if italic else 'normal'}; font-display: block; "
                 f"src: url(data:font/ttf;base64,{base64.b64encode(b).decode()}) format('truetype'); }}")
    print(f'{p.name}: {a.family} {weight}{" italic" if italic else ""}', file=sys.stderr)
if a.js:
    import json
    print('/* Generated by inline-fonts.py: base64 @font-face for ' + a.family + ' (Copy-to-Figma glyph cache). */')
    print('(function () { var s = document.createElement("style"); s.setAttribute("data-inline-fonts", ' + json.dumps(a.family) + '); s.textContent = ' + json.dumps('\n'.join(rules)) + '; document.head.appendChild(s); })();')
else:
    print('\n'.join(rules))
